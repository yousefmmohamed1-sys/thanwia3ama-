    // 4 dynamic wrappers combining with the 250 base quotes => 250 * 4 = 1,000 unique combinations
    private val endings: List<(String, String) -> String> = listOf(
        { quote, name -> "يا $name، $quote 💪" },
        { quote, name -> "$quote — كمل يا بطل يا $name! 🔥" },
        { quote, name -> "رسالة النهاردة ليك يا $name: $quote ✨" },
        { quote, name -> "$quote. حلمك مستنيك يا $name 🚀" }
    )

    val totalCombinationsCount: Int
        get() = baseQuotes.size * endings.size

    fun getRandomQuote(studentName: String, seed: Int? = null): String {
        val cleanName = studentName.trim().ifEmpty { "بطل" }
        val rng = if (seed != null) Random(seed) else Random.Default
        val quote = baseQuotes[rng.nextInt(baseQuotes.size)]
        val wrapper = endings[rng.nextInt(endings.size)]
        return wrapper(quote, cleanName)
    }

    fun getQuoteByIndex(index: Int, studentName: String): String {
        val cleanName = studentName.trim().ifEmpty { "بطل" }
        val safeIndex = ((index % totalCombinationsCount) + totalCombinationsCount) % totalCombinationsCount
        val quoteIdx = safeIndex % baseQuotes.size
        val endingIdx = (safeIndex / baseQuotes.size) % endings.size
        return endings[endingIdx](baseQuotes[quoteIdx], cleanName)
    }
